import csv
import json
from pathlib import Path
from typing import Dict, List
from nexus.utils import get_logger

logger = get_logger(__name__)

class DatasetExporter:
    """Exports simulation data into various dataset formats."""

    @staticmethod
    def _ensure_dir(output_path: str) -> None:
        """Ensures the parent directory exists."""
        Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    def export_logs_csv(self, log_events: List[Dict], output_path: str) -> None:
        """Exports log events to a CSV file."""
        self._ensure_dir(output_path)
        if not log_events:
            logger.warning("No log events to export to CSV.")
            return

        keys = list(log_events[0].keys())
        for event in log_events:
            for k in event.keys():
                if k not in keys:
                    keys.append(k)

        with open(output_path, 'w', newline='', encoding='utf-8') as f:
            writer = csv.DictWriter(f, fieldnames=keys)
            writer.writeheader()
            writer.writerows(log_events)
        logger.info(f"Exported {len(log_events)} events to CSV at {output_path}")

    def export_logs_jsonl(self, log_events: List[Dict], output_path: str) -> None:
        """Exports log events to a JSONL file."""
        self._ensure_dir(output_path)
        with open(output_path, 'w', encoding='utf-8') as f:
            for event in log_events:
                f.write(json.dumps(event) + '\n')
        logger.info(f"Exported {len(log_events)} events to JSONL at {output_path}")

    def export_detection_results(self, results: List[Dict], output_path: str) -> None:
        """Exports detection results as a formatted JSON array."""
        self._ensure_dir(output_path)
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(results, f, indent=2)
        logger.info(f"Exported detection results to {output_path}")

    def export_attack_campaigns(self, campaigns: List[Dict], output_path: str) -> None:
        """Exports attack campaigns dataset."""
        self._ensure_dir(output_path)
        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(campaigns, f, indent=2)
        logger.info(f"Exported attack campaigns to {output_path}")

    def generate_dataset_card(self, metadata: Dict) -> str:
        """Generates a markdown dataset card from metadata."""
        name = metadata.get("name", "NEXUS Dataset")
        description = metadata.get("description", "A dataset generated by NEXUS.")
        author = metadata.get("author", "NEXUS Platform")
        version = metadata.get("version", "1.0")

        md = f"# Dataset Card: {name}\n\n"
        md += f"**Author:** {author}\n"
        md += f"**Version:** {version}\n\n"
        md += f"## Description\n{description}\n\n"
        md += "## Features\n"
        for feature, desc in metadata.get("features", {}).items():
            md += f"- **{feature}**: {desc}\n"
        
        return md

    def get_dataset_stats(self, log_events: List[Dict]) -> Dict:
        """Calculates statistics about the dataset."""
        stats = {
            "total_events": len(log_events),
            "event_types": {}
        }
        for event in log_events:
            etype = event.get("type", "unknown")
            stats["event_types"][etype] = stats["event_types"].get(etype, 0) + 1
        return stats
