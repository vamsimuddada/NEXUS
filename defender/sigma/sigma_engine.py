    # ── Detection ─────────────────────────────────────────────────────────────

    def analyze_log(self, log: dict) -> list[SigmaAlert]:
        """Run all rules against a single log entry. Return matching alerts."""
        alerts = []
        for rule in self.rules:
            if rule.matches(log):
                rule.hit_count += 1
                alerts.append(SigmaAlert(
                    rule_id=rule.rule_id,
                    title=rule.title,
                    severity=rule.severity,
                    technique=rule.technique,
                    log=log,
                ))
        return alerts

    def analyze_stream(self, logs: list[dict]) -> list[SigmaAlert]:
        """Run all rules against a list of log entries."""
        alerts = []
        for log in logs:
            alerts.extend(self.analyze_log(log))
        return alerts

    # ── Rule Management ───────────────────────────────────────────────────────

    def add_rule(self, rule: SigmaRule):
        """Add a new rule (e.g. auto-generated by evolution engine)."""
        # Avoid duplicate IDs
        existing_ids = {r.rule_id for r in self.rules}
        if rule.rule_id not in existing_ids:
            self.rules.append(rule)

    def get_missed_techniques(self, logs: list[dict],
                              detection_results: list[dict] | None = None) -> list[str]:
        """
        Return techniques where the ensemble produced false negatives.

        If detection_results (serialised DetectionResult dicts) are provided,
        use them to find logs where ensemble said 'benign' but label was 'malicious'.
        This is more accurate than technique-level rule coverage because a rule
        can exist and still be bypassed by a crafted log (e.g. NOVA evasion).

        Falls back to technique-vs-rule-coverage comparison if no results provided.
        """
        if detection_results:
            # Find techniques that slipped through the full ensemble
            missed: set[str] = set()
            for r in detection_results:
                if (r.get("true_label") == "malicious"
                        and r.get("ensemble_verdict") == "benign"
                        and r.get("technique")):
                    missed.add(r["technique"])
            return list(missed)

        # Legacy fallback: pure SIGMA coverage gap
        attacked = {log["attack_technique"] for log in logs
                    if log.get("label") == "malicious" and log.get("attack_technique")}
        detected = {a.technique for a in self.analyze_stream(logs)}
        return list(attacked - detected)

    def stats(self) -> dict:
        return {
            "total_rules": len(self.rules),
            "auto_generated": sum(1 for r in self.rules if r.auto_generated),
            "rule_hits": {r.rule_id: r.hit_count for r in self.rules if r.hit_count > 0},
        }

    def save_rules(self, path: str = "data/sigma_rules.json"):
        Path(path).parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w") as f:
            json.dump([r.__dict__ for r in self.rules], f, indent=2)

    def load_rules(self, path: str = "data/sigma_rules.json"):
        if not Path(path).exists():
            return
        with open(path) as f:
            data = json.load(f)
        for item in data:
            rule = SigmaRule(**item)
            self.add_rule(rule)
