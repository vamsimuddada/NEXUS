# ── Rule Model ────────────────────────────────────────────────────────────────

@dataclass
class SigmaRule:
    rule_id: str
    title: str
    description: str
    severity: str               # low | medium | high | critical
    technique: str              # MITRE ATT&CK ID
    conditions: list[dict]      # list of {field, operator, value}
    auto_generated: bool = False
    hit_count: int = 0

    def matches(self, log: dict) -> bool:
        """Return True if ALL conditions match the log entry."""
        for cond in self.conditions:
            field_val = log.get(cond["field"])
            op = cond["operator"]
            target = cond["value"]

            if field_val is None:
                return False

            if op == "eq" and str(field_val) != str(target):
                return False
            if op == "in" and str(field_val) not in [str(v) for v in target]:
                return False
            if op == "contains" and str(target).lower() not in str(field_val).lower():
                return False
            if op == "gte" and not (float(field_val) >= float(target)):
                return False
            if op == "lte" and not (float(field_val) <= float(target)):
                return False
            if op == "regex" and not re.search(target, str(field_val)):
                return False

        return True


# ── Alert ─────────────────────────────────────────────────────────────────────

@dataclass
class SigmaAlert:
    rule_id: str
    title: str
    severity: str
    technique: str
    log: dict
    confidence: float = 1.0


